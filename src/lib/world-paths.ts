/**
 * Simplified world map continent outlines for SVG rendering.
 * Projected to Mercator matching our viewBox (800 x 420):
 *   x = ((lng + 180) / 360) * 800
 *   y = 210 - (ln(tan(PI/4 + latRad/2)) / PI) * 210
 */

// Helper to convert [lng, lat] pairs to SVG path
function toPath(coords: [number, number][]): string {
  return coords
    .map(([lng, lat], i) => {
      const x = ((lng + 180) / 360) * 800;
      const latRad = (lat * Math.PI) / 180;
      const mercN = Math.log(Math.tan(Math.PI / 4 + latRad / 2));
      const y = 210 - (mercN / Math.PI) * 210;
      return `${i === 0 ? "M" : "L"}${x.toFixed(1)},${y.toFixed(1)}`;
    })
    .join(" ") + " Z";
}

